export function countWord(value: number, locale: Locale, kind: 'answers' | 'votes') {
  const category = new Intl.PluralRules(locale).select(Math.abs(value));
  const forms = {
    en: {
      answers: { one: 'answer', few: 'answers', other: 'answers' },
      votes: { one: 'vote', few: 'votes', other: 'votes' },
    },
    uk: {
      answers: { one: 'відповідь', few: 'відповіді', other: 'відповідей' },
      votes: { one: 'голос', few: 'голоси', other: 'голосів' },
    },
  };
  return forms[locale][kind][category === 'one' ? 'one' : category === 'few' ? 'few' : 'other'];
}
